export const GENRES = [...new Set(BOOKS.map((b) => b.genre))].sort();
export const AUTHORS = [...new Set(BOOKS.map((b) => b.author))].sort();
export const SERIES = [
  ...new Set(BOOKS.map((b) => b.series).filter(Boolean)),
] as string[];

export const getFeaturedBooks = () => BOOKS.filter((b) => b.isFeatured);
export const getBestsellers = () => BOOKS.filter((b) => b.isBestseller);
export const getNewArrivals = () => BOOKS.filter((b) => b.isNewArrival);
export const getBookById = (id: string) => BOOKS.find((b) => b.id === id);
export const getBooksByAuthor = (author: string) =>
  BOOKS.filter((b) => b.author === author);
export const getBooksByGenre = (genre: string) =>
  BOOKS.filter((b) => b.genre === genre);
export const searchBooks = (query: string) => {
  const q = query.toLowerCase();
  return BOOKS.filter(
    (b) =>
      b.title.toLowerCase().includes(q) ||
      b.author.toLowerCase().includes(q) ||
      b.penName?.toLowerCase().includes(q) ||
      b.description.toLowerCase().includes(q),
  );
};
